#!/usr/bin/env python
"""Export the layout ground truth in Ultralytics YOLO format (§6).

    python scripts/export_layout_dataset.py --profile v1

The structural regions are already generated -- they live under the "layout"
key of each annotations/fields/*.json, alongside the field, ocr and table views
of the same render. This script only reshapes them; it never invents a box.

Two things it deliberately does NOT do:

  * It does not re-split. The splits under datasets/splits/ are grouped by
    parcel family so that two documents about the same parcel cannot land on
    opposite sides of the train/val boundary. Re-splitting here would leak.
  * It does not copy images. They are symlinked, because a second copy of a
    1000-image corpus is a copy that can go stale.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATASETS = REPO_ROOT / "datasets"

#: Class order is pinned, not derived from whatever the corpus happens to
#: contain: a training run and an inference run that disagree about which
#: integer means "table" fail silently and look like poor accuracy.
CLASSES = ["header", "table"]
CLASS_INDEX = {name: i for i, name in enumerate(CLASSES)}

SPLITS = ["train", "val", "test"]


def to_yolo_line(box: dict, width: int, height: int) -> str | None:
    """One normalised `cls cx cy w h` line, or None for an unusable box."""
    kind = box.get("type")
    if kind not in CLASS_INDEX:
        return None
    x1, y1, x2, y2 = box["bbox"]
    if x2 <= x1 or y2 <= y1:
        return None

    # Clamp before normalising. A box that pokes one pixel outside the frame is
    # a rounding artefact of the corner-bounds arithmetic, not a reason to drop
    # ground truth -- but a coordinate above 1.0 makes Ultralytics reject the
    # whole label file.
    x1, y1 = max(0, x1), max(0, y1)
    x2, y2 = min(width, x2), min(height, y2)
    if x2 <= x1 or y2 <= y1:
        return None

    cx = (x1 + x2) / 2 / width
    cy = (y1 + y2) / 2 / height
    bw = (x2 - x1) / width
    bh = (y2 - y1) / height
    return f"{CLASS_INDEX[kind]} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}"


def link(src: Path, dst: Path) -> None:
    if dst.is_symlink() or dst.exists():
        dst.unlink()
    dst.symlink_to(src.resolve())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", default="v1")
    parser.add_argument("--out", default="yolo-layout")
    args = parser.parse_args()

    out_root = DATASETS / args.out
    counts: Counter[str] = Counter()
    per_split: dict[str, int] = {}

    for split in SPLITS:
        split_file = DATASETS / "splits" / f"{split}.{args.profile}.jsonl"
        if not split_file.exists():
            raise SystemExit(
                f"missing {split_file}; run scripts/split_dataset.py "
                f"--profile {args.profile}"
            )

        img_dir = out_root / "images" / split
        lbl_dir = out_root / "labels" / split
        for d in (img_dir, lbl_dir):
            d.mkdir(parents=True, exist_ok=True)
        for stale in list(img_dir.iterdir()) + list(lbl_dir.iterdir()):
            stale.unlink()

        rows = [json.loads(line) for line in split_file.read_text().splitlines() if line]
        for row in rows:
            ann = json.loads((DATASETS / row["annotation"]).read_text())
            image = DATASETS / row["degraded_image"]
            if not image.exists():
                raise SystemExit(f"missing image {image}; regenerate the corpus")

            lines = []
            for box in ann["layout"]:
                line = to_yolo_line(box, ann["width"], ann["height"])
                if line is not None:
                    lines.append(line)
                    counts[box["type"]] += 1

            stem = row["document_id"]
            link(image, img_dir / f"{stem}{image.suffix}")
            # An empty .txt is meaningful to Ultralytics: it means "this image
            # genuinely has no objects", as opposed to an absent file.
            (lbl_dir / f"{stem}.txt").write_text("\n".join(lines) + ("\n" if lines else ""))

        per_split[split] = len(rows)

    data_yaml = out_root / "data.yaml"
    names = "\n".join(f"  {i}: {name}" for i, name in enumerate(CLASSES))
    data_yaml.write_text(
        "# Generated by scripts/export_layout_dataset.py -- do not hand-edit.\n"
        f"path: {out_root.resolve()}\n"
        "train: images/train\n"
        "val: images/val\n"
        "test: images/test\n"
        f"names:\n{names}\n"
    )

    print(f"wrote {out_root}")
    for split in SPLITS:
        print(f"  {split:5s} {per_split[split]:4d} images")
    print(f"  boxes: {dict(counts)}")
    print(f"  data:  {data_yaml}")


if __name__ == "__main__":
    main()
